const Order = require("../../models/Order");
const { normalizeOrderStatus } = require("../../utils/order-status");
const { emitOrderUpdate } = require("../../utils/realtime");

const getAllOrdersOfAllUsers = async (req, res) => {
  try {
    const orders = await Order.find({});

    if (!orders.length) {
      return res.status(404).json({
        success: false,
        message: "No orders found!",
      });
    }

    res.status(200).json({
      success: true,
      data: orders,
    });
  } catch (e) {
    console.log(e);
    res.status(500).json({
      success: false,
      message: "Some error occured!",
    });
  }
};

const getOrderDetailsForAdmin = async (req, res) => {
  try {
    const { id } = req.params;

    const order = await Order.findById(id);

    if (!order) {
      return res.status(404).json({
        success: false,
        message: "Order not found!",
      });
    }

    res.status(200).json({
      success: true,
      data: order,
    });
  } catch (e) {
    console.log(e);
    res.status(500).json({
      success: false,
      message: "Some error occured!",
    });
  }
};

const updateOrderStatus = async (req, res) => {
  try {
    const { id } = req.params;
    const { orderStatus, deliveredAt } = req.body;
    const normalizedStatus = normalizeOrderStatus(orderStatus);

    const order = await Order.findById(id);

    if (!order) {
      return res.status(404).json({
        success: false,
        message: "Order not found!",
      });
    }

    order.orderStatus = normalizedStatus;

    if (deliveredAt) {
      order.deliveredAt = new Date(deliveredAt);
    }

    if (normalizedStatus === "delivered" && !order.deliveredAt) {
      order.deliveredAt = new Date();
    }

    order.orderUpdateDate = new Date();
    await order.save();

    emitOrderUpdate(order);

    res.status(200).json({
      success: true,
      message: "Order status is updated successfully!",
      data: order,
    });
  } catch (e) {
    console.log(e);
    res.status(500).json({
      success: false,
      message: "Some error occured!",
    });
  }
};

module.exports = {
  getAllOrdersOfAllUsers,
  getOrderDetailsForAdmin,
  updateOrderStatus,
};
